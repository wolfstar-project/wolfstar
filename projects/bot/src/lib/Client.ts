// Loads the `broker` client option and `container.broker` types, the Stars CLI injects the runtime import:
/// <reference types="@wolfstar/plugin-broker/register" />

import { envParseBoolean, envParseInteger, envParseString } from '@wolfstar/env-utilities';
import { container } from '@wolfstar/http-framework';
import { createBroker, forwardGatewayDispatches, replayGatewayDispatches } from '@wolfstar/plugin-broker';
import { createRedisCache, createRedisSessionStore } from '@wolfstar/plugin-cache';
import { GatewayClient } from '@wolfstar/plugin-gateway';
import * as Sentry from '@sentry/node';
import { GatewayIntentBits } from 'discord-api-types/v10';
import { Redis, type RedisOptions } from 'ioredis';
import { fileURLToPath } from 'node:url';

/**
 * Whether this process is a worker: it never connects to Discord, it replays the dispatches the gateway process
 * forwards onto the broker's stream (see `BROKER_ENABLED`) on a client sharing its Redis cache.
 */
export const isWorker = () => envParseString('BOT_MODE', 'gateway') === 'worker';

export function createClient(options: ClientOptions = {}) {
	const worker = isWorker();

	container.redis = new Redis({
		...options.redis,
		lazyConnect: true,
		host: envParseString('REDIS_HOST'),
		port: envParseInteger('REDIS_PORT'),
		db: envParseInteger('REDIS_DB'),
		password: envParseString('REDIS_PASSWORD')
	});

	// The client registers itself as `container.gatewayClient`:
	// oxlint-disable-next-line no-new
	new GatewayClient({
		discordToken: envParseString('DISCORD_TOKEN'),
		discordPublicKey: envParseString('DISCORD_PUBLIC_KEY'),
		intents:
			GatewayIntentBits.GuildModeration |
			GatewayIntentBits.GuildExpressions |
			GatewayIntentBits.GuildInvites |
			GatewayIntentBits.GuildMembers |
			GatewayIntentBits.GuildMessageReactions |
			GatewayIntentBits.GuildMessages |
			GatewayIntentBits.GuildVoiceStates |
			GatewayIntentBits.Guilds |
			GatewayIntentBits.MessageContent,
		cache: createRedisCache({ redis: container.redis, prefix: 'wolfstar:cache' }),
		// Keeps the shards' sessions in Redis, so a restart resumes them instead of identifying again:
		sessionStore: createRedisSessionStore({ redis: container.redis, prefix: 'wolfstar:sessions' }),
		api: {
			automaticallyConnect: !worker && envParseBoolean('API_ENABLED', true),
			listenOptions: {
				host: envParseString('API_HOST', '127.0.0.1'),
				port: envParseInteger('API_PORT', 8282)
			},
			origin: envParseString('API_ORIGIN', '*'),
			prefix: envParseString('API_PREFIX', '') || undefined
		},
		i18n: {
			defaultLanguageDirectory: fileURLToPath(new URL('../locales', import.meta.url)),
			defaultName: 'en-US',
			defaultNS: 'globals'
		},
		subcommandsAdvanced: {
			nameCommandsAutogenerated: true
		},
		// A worker reads the dispatches from the stream, as a member of a consumer group sharing them with its peers:
		broker: worker
			? {
					redis: container.redis,
					stream: envParseString('BROKER_STREAM', 'wolfstar:events'),
					group: envParseString('BROKER_GROUP', 'workers'),
					consumer: envParseString('BROKER_CONSUMER', 'worker-1'),
					shutdownSignals: ['SIGTERM', 'SIGINT']
				}
			: undefined
	});

	if (worker) replayGatewayDispatches(container.broker, container.gatewayClient);

	// Publishes every gateway dispatch onto a Redis stream, for workers that replay them (see `@wolfstar/plugin-broker`):
	if (!worker && envParseBoolean('BROKER_ENABLED', false)) {
		const broker = createBroker({
			redis: container.redis,
			stream: envParseString('BROKER_STREAM', 'wolfstar:events'),
			maxLength: envParseInteger('BROKER_MAX_LENGTH', 100_000)
		});
		forwardGatewayDispatches(container.gatewayClient, broker);
	}

	const srcFolderURL = new URL('..', import.meta.url);
	container.stores.registerPath(fileURLToPath(srcFolderURL));

	// Load in Sentry for error logging
	if (process.env.SENTRY_DSN) {
		Sentry.init({
			dsn: process.env.SENTRY_DSN,
			integrations: [
				Sentry.modulesIntegration(),
				Sentry.functionToStringIntegration(),
				Sentry.linkedErrorsIntegration(),
				Sentry.consoleIntegration(),
				Sentry.httpIntegration({ breadcrumbs: true }),
				Sentry.rewriteFramesIntegration({ root: fileURLToPath(new URL('..', srcFolderURL)) })
			]
		});
	}
}

export async function loadAll() {
	await container.redis.connect();

	if (isWorker()) {
		// No HTTP server and no gateway connection: load the pieces, then start reading the stream:
		await container.gatewayClient.load();
		await container.broker.start();
		return;
	}

	// Loads the pieces, starts the HTTP interactions endpoint, then connects the gateway shards:
	await container.gatewayClient.start({
		listen: {
			address: envParseString('HTTP_ADDRESS', '127.0.0.1'),
			port: envParseInteger('HTTP_PORT', 3000)
		}
	});
}

export interface ClientOptions {
	redis?: Omit<RedisOptions, 'lazyConnect' | 'host' | 'port' | 'db' | 'password'>;
}

